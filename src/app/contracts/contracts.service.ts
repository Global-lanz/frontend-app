  postContract(contractData: Partial<Contract>) { //Partial, because id will be generated by backend
    return this.http.post<{contractData: Partial<Contract>}>(`${this.baseUrl}/finance/contract`, {
      ...contractData
    })
  }
    
  putContract(id:string, contractData: Contract) {
    return this.http.put<{contractData: Contract}>(`${this.baseUrl}/finance/contract/${id}`, {
      ...contractData
    })
  }

  postContractStatus(id:string, toStatus: string) {
    return this.http.post<{id:string, toStatus:string}>(`${this.baseUrl}/finance/contract/${id}/status`, {
      status: toStatus
    })
  }

