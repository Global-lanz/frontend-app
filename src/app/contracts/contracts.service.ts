  private http = inject(HttpClient);
  baseUrl = 'http://localhost:8080';
  
  getAllContracts() {
    this.isLoading.set(true);
    // this.errorMessage.set(null);
    this.getContracts().subscribe({
      next: response => {
          this.contracts.set(response);
          console.log(response);
        },
        error: error => {
          console.error('Error fetching contracts', error);
          this.messageService.setMessage('error',`Error fetching contracts: ${error.message}`);
          // this.errorMessage.set(error.message);
        },
        complete: () => {this.isLoading.set(false)},
    })
  }

  
  contractsByCustomerResource(customerIdSignal: Signal<string | undefined>): HttpResourceRef<{ content?: Contract[] } | undefined> {
    return httpResource(() =>
      `${this.baseUrl}/finance/contract/search?customerId=${customerIdSignal()}&pageNumber=0&pageSize=10`
    );
  }


